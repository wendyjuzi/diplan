def _timer_add(name: str, elapsed: float, count: int = 1):
    stats = globals().setdefault("_TOG_STAGE_TIMERS", {})
    item = stats.setdefault(name, {"wall_time_s": 0.0, "calls": 0})
    item["wall_time_s"] += float(elapsed)
    item["calls"] += int(count)


class LocalSubgraphBackend:
    def __init__(self, row: dict):
        self.row = row
        self.question = row["question"]
        self.answers = {str(x) for x in _as_list(row.get("a_entity"))}
        self.oracle_path = list(row.get("oracle_path") or [])
        self.trap_path = list(row.get("trap_path") or [])
        self.q_entity = _as_list(row.get("q_entity"))
        self.adj = {}
        self.rev = {}
        self.names = set()
        self._distance_cache = {}
        for s, r, o in row.get("graph") or []:
            s, r, o = str(s), str(r), str(o)
            self.adj.setdefault(s, {}).setdefault(r, [])
            if o not in self.adj[s][r]:
                self.adj[s][r].append(o)
            self.rev.setdefault(o, {}).setdefault(r, [])
            if s not in self.rev[o][r]:
                self.rev[o][r].append(s)
            self.names.add(s)
            self.names.add(o)

    def id2name(self, entity_id: str) -> str:
        return str(entity_id)

    def topic_entity(self):
        return {str(e): self.id2name(str(e)) for e in self.q_entity}

    def relations(self, entity_id: str, pre_relations, pre_head, remove_unnecessary=True):
        head_relations = sorted(self.adj.get(entity_id, {}).keys())
        tail_relations = sorted(self.rev.get(entity_id, {}).keys())
        if remove_unnecessary:
            head_relations = [r for r in head_relations if not _abandon_rels(r)]
            tail_relations = [r for r in tail_relations if not _abandon_rels(r)]
        if len(pre_relations) != 0 and pre_head != -1:
            tail_relations = [r for r in tail_relations if pre_head or r not in pre_relations]
            head_relations = [r for r in head_relations if (not pre_head) or r not in pre_relations]
        return sorted(set(head_relations)), sorted(set(tail_relations))

    def entity_search(self, entity_id: str, relation: str, head=True):
        if head:
            return list(self.adj.get(entity_id, {}).get(relation, []))
        return list(self.rev.get(entity_id, {}).get(relation, []))

    def shortest_answer_distance(self, entity_id: str, max_hops: int = 6):
        """Shortest undirected relation-step distance to any answer entity."""
        key = (str(entity_id), int(max_hops))
        if key in self._distance_cache:
            return self._distance_cache[key]
        start = str(entity_id)
        if start in self.answers:
            self._distance_cache[key] = 0
            return 0
        frontier = {start}
        seen = {start}
        for depth in range(1, max_hops + 1):
            nxt = set()
            for node in frontier:
                for values in self.adj.get(node, {}).values():
                    nxt.update(str(x) for x in values)
                for values in self.rev.get(node, {}).values():
                    nxt.update(str(x) for x in values)
            nxt -= seen
            if nxt & self.answers:
                self._distance_cache[key] = depth
                return depth
            if not nxt:
                break
            seen.update(nxt)
            frontier = nxt
        self._distance_cache[key] = None
        return None

    def answer_reaching_relations(self, entity_id: str, remaining_steps: int):
        """Relations that minimize reachable distance to an answer from this entity."""
        candidates = []
        for relation, values in self.adj.get(str(entity_id), {}).items():
            candidates.append((relation, True, values))
        for relation, values in self.rev.get(str(entity_id), {}).items():
            candidates.append((relation, False, values))
        best_distance = None
        best_relations = set()
        for relation, _head, values in candidates:
            distances = [
                self.shortest_answer_distance(str(x), max(0, remaining_steps - 1))
                for x in values
            ]
            distances = [d for d in distances if d is not None]
            if not distances:
                continue
            distance = 1 + min(distances)
            if best_distance is None or distance < best_distance:
                best_distance = distance
                best_relations = {relation}
            elif distance == best_distance:
                best_relations.add(relation)
        return best_relations


def _abandon_rels(relation: str) -> bool:
    return (
        relation == "type.object.type"
        or relation == "type.object.name"
        or relation.startswith("common.")
        or relation.startswith("freebase.")
        or "sameAs" in relation
    )


def relation_label(relation: str) -> str:
    return " ".join(t for t in relation.replace(".", " ").replace("_", " ").split() if t)


def relation_search_prune_local(backend: LocalSubgraphBackend, entity_id, entity_name, pre_relations, pre_head, question, args):
    _stage_t0 = time.time()
    def _finish(value):
        _timer_add("relation_prune", time.time() - _stage_t0)
        return value
    head_relations, tail_relations = backend.relations(
        entity_id,
        pre_relations,
        pre_head,
        remove_unnecessary=bool(args.remove_unnecessary_rel),
    )
    total_relations = sorted(set(head_relations + tail_relations))
    if not total_relations:
        return _finish([])
    max_prompt_relations = int(getattr(args, "max_prompt_relations", 64))
    prompt_relations = sorted(total_relations, key=lambda r: (-_overlap(relation_label(r), question), r))[:max_prompt_relations]
    rerank_pool_size = 0
    pool_strategy = str(getattr(args, "diplan_pool_strategy", "lexical"))
    if _is_diplan_strategy(args) or _is_mcts_strategy(args):
        rerank_pool_size = int(getattr(args, "diplan_rerank_pool_size", 0))
    relation_prune_tools = str(getattr(args, "relation_prune_tools", "") or getattr(args, "prune_tools", "llm"))
    if relation_prune_tools == "llm":
        # Use official ToG relation-prune prompt, but expose human-readable labels
        # while keeping original relation IDs parseable by clean_relations.
        labelled = [f"{r} (label: {relation_label(r)})" for r in prompt_relations]
        prompt = construct_relation_prune_prompt(question, entity_name, labelled, args)
        try:
            result = run_llm(prompt, args.temperature_exploration, args.max_length, args.opeani_api_keys, args.LLM_type)
            # The official parser expects exact relation strings; strip labels before parse.
            for r in prompt_relations:
                result = result.replace(f"{r} (label: {relation_label(r)})", r)
            flag, rels = clean_relations(result, entity_id, head_relations)
            if flag:
                if rerank_pool_size > args.width:
                    return _finish(_expand_relation_pool(
                        entity_id,
                        rels,
                        total_relations,
                        head_relations,
                        question,
                        rerank_pool_size,
                        pool_strategy=pool_strategy,
                    ))
                return _finish(rels)
        except Exception as exc:
            print(f"[ToG relation prune] LLM failed, fallback to lexical: {exc}", flush=True)
    # Deterministic fallback: relation-label lexical overlap.
    if pool_strategy == "all_legal" and rerank_pool_size > 0:
        limit = min(len(total_relations), rerank_pool_size)
    else:
        limit = rerank_pool_size if rerank_pool_size > args.width else args.width
    ranked_all = _rank_pool_relations(total_relations, question, pool_strategy)
    ranked = ranked_all[: limit]
    return _finish([
        {"entity": entity_id, "relation": r, "score": 1.0 / (i + 1), "head": r in head_relations}
        for i, r in enumerate(ranked)
    ])


def _expand_relation_pool(entity_id, seed_rels, total_relations, head_relations, question, pool_size, pool_strategy="lexical"):
    """Let ToG build the action space, then expose a larger legal pool to DiPLaN.

    Original ToG often returns only ``width`` relations (e.g. 3). If DiPLaN only
    reranks those three, it can look active while having almost no room to help.
    This keeps ToG/LLM relations first, then fills with lexical legal relations
    so candidate-conditioned DiPLaN can choose from top-k actions before we cut
    back to the execution width.
    """
    out = []
    seen = set()
    for i, item in enumerate(seed_rels or []):
        rel = item.get("relation") if isinstance(item, dict) else str(item)
        if rel in seen or rel not in total_relations:
            continue
        cc = dict(item) if isinstance(item, dict) else {}
        cc.setdefault("entity", entity_id)
        cc["relation"] = rel
        cc.setdefault("score", 1.0 / (i + 1))
        cc.setdefault("head", rel in head_relations)
        out.append(cc)
        seen.add(rel)
    ranked = _rank_pool_relations(total_relations, question, pool_strategy)
    for j, rel in enumerate(ranked):
        if len(out) >= pool_size:
            break
        if rel in seen:
            continue
        out.append({
            "entity": entity_id,
            "relation": rel,
            "score": 0.25 / (j + 1),
            "head": rel in head_relations,
        })
        seen.add(rel)
    return out


def _rank_pool_relations(relations, question, pool_strategy="lexical"):
    if pool_strategy == "all_legal":
        # High-recall mode inspired by relation-exploration KGQA: do not let
        # lexical/LLM pruning become a hard bottleneck before learned reranking.
        return sorted(relations)
    return sorted(relations, key=lambda r: (-_overlap(relation_label(r), question), r))


def _overlap(text: str, question: str) -> float:
    q = {t.lower() for t in question.replace("?", " ").replace(",", " ").split() if t}
    r = {t.lower() for t in text.replace(".", " ").replace("_", " ").split() if t}
    return len(q & r) / max(1, len(r))


def entity_score_local(backend: LocalSubgraphBackend, question, entity_candidates_id, score, relation, args):
    _stage_t0 = time.time()
    def _finish(value):
        _timer_add("entity_prune", time.time() - _stage_t0)
        return value
    entity_candidates = [backend.id2name(eid) for eid in entity_candidates_id]
    if len(entity_candidates) == 0:
        return _finish(([0.0], [], []))
    if len(entity_candidates) == 1:
        return _finish(([score], entity_candidates, entity_candidates_id))
    entity_prune_tools = str(getattr(args, "entity_prune_tools", "") or getattr(args, "prune_tools", "llm"))
    if entity_prune_tools == "llm":
        prompt = construct_entity_score_prompt(question, relation, entity_candidates)
        result = run_llm(prompt, args.temperature_exploration, args.max_length, args.opeani_api_keys, args.LLM_type)
        return _finish(([float(x) * score for x in clean_scores(result, entity_candidates)], entity_candidates, entity_candidates_id))
    if entity_prune_tools in {"lexical", "heuristic"}:
        q = {t.lower() for t in question.replace("?", " ").replace(",", " ").split() if t}
        vals = []
        for name in entity_candidates:
            toks = {t.lower() for t in str(name).replace("_", " ").replace(".", " ").split() if t}
            overlap = len(q & toks) / max(1, len(toks))
            vals.append(float(score) * (0.25 + overlap))
        if not vals:
            vals = [float(score) / max(1, len(entity_candidates))]
        return _finish((vals, entity_candidates, entity_candidates_id))
    # fallback: keep equal mass
    return _finish(([score / len(entity_candidates)] * len(entity_candidates), entity_candidates, entity_candidates_id))


