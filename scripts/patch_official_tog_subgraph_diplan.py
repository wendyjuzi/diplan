def relation_first_select(
    total_entities_id,
    total_relations,
    total_candidates,
    total_topic_entities,
    total_head,
    total_scores,
    relation_scores,
    args,
):
    """Select relations before entities so entity pruning cannot erase a good action.

    Official ToG's entity_prune ranks entity candidates directly. That is faithful,
    but for ToG-DiPLaN diagnostics it can hide whether relation-level planning
    helped: an oracle relation can be ranked high, expanded, then disappear because
    its entities receive weaker local entity scores. This mode first keeps diverse
    high-scoring relations, then attaches the best entity for each kept relation.
    """
    groups = {}
    for eid, rel, cand, topic, head, ent_score in zip(
        total_entities_id,
        total_relations,
        total_candidates,
        total_topic_entities,
        total_head,
        total_scores,
    ):
        key = (rel, bool(head))
        rel_score = float(relation_scores.get(key, relation_scores.get(rel, ent_score)))
        item = {
            "entity_id": eid,
            "relation": rel,
            "candidate": cand,
            "topic_entity": topic,
            "head": bool(head),
            "entity_score": float(ent_score),
            "relation_score": rel_score,
        }
        groups.setdefault(key, []).append(item)
    if not groups:
        return False, [], [], [], []

    selected = []
    for items in groups.values():
        best_entity = max(items, key=lambda x: (x["entity_score"], x["relation_score"]))
        selected.append(best_entity)
    selected.sort(key=lambda x: (x["relation_score"], x["entity_score"]), reverse=True)
    relation_first_k = int(args.relation_first_k or args.num_retain_entity)
    selected = selected[: max(1, relation_first_k)]

    chain_of_entities = [x["candidate"] for x in selected]
    entities_id = [x["entity_id"] for x in selected]
    pre_relations = [x["relation"] for x in selected]
    pre_heads = [x["head"] for x in selected]
    return True, chain_of_entities, entities_id, pre_relations, pre_heads


def pog_rerank_candidates(backend, candidates, executed_prefix, args):
    """PoG-only candidate ordering without DiPLaN checkpoints."""
    if not candidates:
        return candidates
    out = []
    for cand in candidates:
        cc = dict(cand)
        guidance, memory, reflection = _pog_relation_signals(
            backend,
            cc,
            executed_prefix,
            remaining_horizon=max(1, int(args.depth) - len(executed_prefix)),
            fanout_penalty=float(args.pog_fanout_penalty),
        )
        pog_score = (
            float(args.pog_guidance_weight) * float(guidance)
            + float(args.pog_memory_weight) * float(memory)
            + float(args.pog_reflection_weight) * float(reflection)
        )
        cc["pog_guidance_score"] = float(guidance)
        cc["pog_memory_score"] = float(memory)
        cc["pog_reflection_score"] = float(reflection)
        cc["pog_score"] = float(pog_score)
        cc["score"] = float(cc.get("score", 0.0)) + float(pog_score)
        out.append(cc)
    return sorted(out, key=lambda x: x["score"], reverse=True)


